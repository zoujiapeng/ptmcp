"""ptmcp.borrow - reuse the strong parts of other Packet Tracer MCP projects.

`packet-tracer-mcp` (MIT) ships well-tested *CLI generators* for VLANs, trunks,
router sub-interfaces, ACLs, NAT, port-security and hardening. We do not rewrite
those: this module calls them (if the package is installed) and hands the
resulting IOS lines to our own terminal runner.

    from ptmcp.borrow import vlan_cli
    lines = vlan_cli(vlans=[{"id": 10, "name": "USERS"}],
                     access_ports=[{"port": "f0/1", "vlan": 10}],
                     switch_model="2960-24TT")
    pt.cli("S1", ["enable", "configure terminal"] + lines)

If `packet_tracer_mcp` is missing, a clear ImportError explains how to add it;
nothing else in ptmcp depends on it.
"""
from __future__ import annotations

from typing import Any

HELP = ("pip install packet-tracer-mcp  "
        "(MIT; https://github.com/Mats2208/MCP-Packet-Tracer)")


def _mod(path: str):
    try:
        return __import__(path, fromlist=["x"])
    except ImportError as exc:                                  # pragma: no cover
        raise ImportError(f"optional dependency missing: {exc}. Install with: {HELP}") from None


def _model(module: str, name: str, data: Any):
    """Build one of their pydantic models from a plain dict (or pass it through)."""
    mod = _mod(module)
    cls = getattr(mod, name, None)
    if cls is None:
        raise AttributeError(f"{module}.{name} not found - generator API changed")
    if isinstance(data, cls):
        return data
    if hasattr(cls, "model_validate"):
        return cls.model_validate(data)
    return cls(**data)


def vlan_cli(vlans: list[dict], access_ports: list[dict] | None = None,
             trunks: list[dict] | None = None, switch_model: str = "2960-24TT") -> list[str]:
    """`vlan …` + `switchport …` lines, generated by packet-tracer-mcp."""
    gen = _mod("packet_tracer_mcp.infrastructure.generator.vlan_cli_generator")
    base = "packet_tracer_mcp.domain.models.vlans"
    return list(gen.generate_switch_vlan_cli(
        [_model(base, "VLANConfig", v) for v in vlans],
        [_model(base, "AccessPortConfig", a) for a in (access_ports or [])],
        [_model(base, "TrunkConfig", t) for t in (trunks or [])],
        supports_encap=bool(gen.switch_supports_encap(switch_model)),
    ))


def subinterface_cli(subinterfaces: list[dict]) -> list[str]:
    """Router-on-a-stick sub-interface lines, generated by packet-tracer-mcp."""
    gen = _mod("packet_tracer_mcp.infrastructure.generator.vlan_cli_generator")
    base = "packet_tracer_mcp.domain.models.vlans"
    return list(gen.generate_router_subinterface_cli(
        [_model(base, "SubinterfaceConfig", s) for s in subinterfaces]))


def acl_cli(plan: dict, binding: dict | None = None) -> list[str]:
    """Standard/extended ACL lines, generated by packet-tracer-mcp."""
    gen = _mod("packet_tracer_mcp.infrastructure.generator.acl_cli_generator")
    base = "packet_tracer_mcp.domain.models.acls"
    lines = list(gen.generate_acl_cli(_model(base, "ACLPlan", plan)))
    if binding:
        lines += list(gen.generate_acl_binding_cli(_model(base, "ACLBinding", binding)))
    return lines


def nat_cli(config: dict) -> list[str]:
    """NAT lines (static / PAT), generated by packet-tracer-mcp."""
    gen = _mod("packet_tracer_mcp.infrastructure.generator.nat_cli_generator")
    base = "packet_tracer_mcp.domain.models.nat"
    cfg = _model(base, "NATConfig", config)
    return list(gen.generate_nat_interface_cli(cfg)) + list(gen.generate_nat_body_cli(cfg))


def hardening_cli(config: dict) -> list[str]:
    """Device hardening lines (ssh, local user, enable secret…)."""
    gen = _mod("packet_tracer_mcp.infrastructure.generator.hardening_cli_generator")
    base = "packet_tracer_mcp.domain.models.hardening"
    return list(gen.generate_hardening_cli(_model(base, "HardeningConfig", config)))


def port_security_cli(config: dict) -> list[str]:
    """Switch port-security lines."""
    gen = _mod("packet_tracer_mcp.infrastructure.generator.switch_security_cli_generator")
    base = "packet_tracer_mcp.domain.models.switch_security"
    return list(gen.generate_port_security_cli(_model(base, "PortSecurityConfig", config)))
